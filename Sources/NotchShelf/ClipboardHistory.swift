import AppKit

struct ClipEntry: Identifiable, Codable, Equatable {
    var id = UUID()
    var text: String?
    var imageFile: String?        // имя файла в папке Clips
    var date: Date
    var isPinned = false
    var appName: String?

    var imageURL: URL? { imageFile.map { ClipboardHistory.directory.appendingPathComponent($0) } }
}

/// История буфера обмена: текст и картинки. Пропускает известные метки секретного содержимого;
/// секреты без таких меток могут попасть в историю.
@MainActor
final class ClipboardHistory: ObservableObject {
    @Published private(set) var entries: [ClipEntry] = []
    var onToast: ((String) -> Void)?

    private let settings: AppSettings
    private var lastChange: Int
    private var timer: Timer?

    nonisolated static var directory: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("NotchShelf/Clips", isDirectory: true)
    }
    private static var indexURL: URL { directory.appendingPathComponent("history.json") }

    /// Метки, которыми менеджеры паролей помечают «секретное» содержимое буфера.
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
    ]

    init(settings: AppSettings) {
        self.settings = settings
        lastChange = NSPasteboard.general.changeCount
        try? FileManager.default.createDirectory(at: Self.directory, withIntermediateDirectories: true)
        load()
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    // MARK: Чтение буфера

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard settings.clipboardEnabled else { return }

        let types = pb.types ?? []
        if types.contains(where: { Self.skippedTypes.contains($0.rawValue) }) { return }
        if types.contains(.fileURL) { return }   // копирование файлов в Finder не храним

        let app = NSWorkspace.shared.frontmostApplication?.localizedName

        if let text = pb.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            var pinned = false
            if let idx = entries.firstIndex(where: { $0.text == text }) {
                pinned = entries[idx].isPinned
                entries.remove(at: idx)
            }
            entries.insert(ClipEntry(text: text, date: Date(), isPinned: pinned, appName: app), at: 0)
        } else if let image = NSImage(pasteboard: pb), let png = image.pngData {
            let name = UUID().uuidString + ".png"
            do {
                try png.write(to: Self.directory.appendingPathComponent(name))
                entries.insert(ClipEntry(imageFile: name, date: Date(), appName: app), at: 0)
            } catch { return }
        } else {
            return
        }
        trim()
        save()
    }

    // MARK: Действия

    func copy(_ entry: ClipEntry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let text = entry.text {
            pb.setString(text, forType: .string)
        } else if let url = entry.imageURL, let image = NSImage(contentsOf: url) {
            pb.writeObjects([image])
        }
        lastChange = pb.changeCount   // не дублируем собственное копирование
        if let idx = entries.firstIndex(where: { $0.id == entry.id }) {
            var e = entries.remove(at: idx)
            e.date = Date()
            entries.insert(e, at: 0)
            save()
        }
        onToast?("Скопировано в буфер обмена")
    }

    func togglePin(_ entry: ClipEntry) {
        guard let idx = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[idx].isPinned.toggle()
        save()
    }

    func remove(_ entry: ClipEntry) {
        entries.removeAll { $0.id == entry.id }
        deleteImage(of: entry)
        save()
    }

    func clearUnpinned() {
        let removed = entries.filter { !$0.isPinned }
        guard !removed.isEmpty else { return }
        removed.forEach { deleteImage(of: $0) }
        entries.removeAll { !$0.isPinned }
        save()
        onToast?("История очищена")
    }

    // MARK: Хранение

    private func trim() {
        let limit = max(10, settings.clipboardLimit)
        var unpinnedCount = 0
        var kept: [ClipEntry] = []
        for e in entries {
            if e.isPinned { kept.append(e); continue }
            unpinnedCount += 1
            if unpinnedCount <= limit { kept.append(e) } else { deleteImage(of: e) }
        }
        entries = kept
    }

    private func deleteImage(of entry: ClipEntry) {
        if let url = entry.imageURL { try? FileManager.default.removeItem(at: url) }
    }

    private func load() {
        guard let data = try? Data(contentsOf: Self.indexURL),
              let saved = try? JSONDecoder().decode([ClipEntry].self, from: data) else { return }
        entries = saved.filter { $0.text != nil || ($0.imageURL.map { FileManager.default.fileExists(atPath: $0.path) } ?? false) }
    }

    private func save() {
        if let data = try? JSONEncoder().encode(entries) {
            try? data.write(to: Self.indexURL, options: .atomic)
        }
    }
}

extension NSImage {
    var pngData: Data? {
        guard let tiff = tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}
